'use strict';

// Developer-only tool; the generated classic script needs no library or build.
// Fraction.js 5.3.4, rawify/Fraction.js@9aa0f355e5d6c25d10bce7a7ab25a3a4bd074942.
// The unchanged CommonJS distribution and full MIT license are in vendor/.
// Reject the upstream Number fallback before loading the library.
if (typeof BigInt !== 'function' || typeof BigInt(1) !== 'bigint') {
  throw new Error('The 24-point generator requires native BigInt.');
}

const Fraction = require('../vendor/fraction.cjs');
const { writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const CONTENT_VERSION = '1';

function valueKey(value) {
  return `${value.s * value.n}/${value.d}`;
}

function solveCards(cards) {
  if (!Array.isArray(cards) || cards.length !== 4 ||
      !cards.every(card => Number.isInteger(card) && card >= 1 && card <= 9)) {
    throw new TypeError('Expected four integer cards in 1..9.');
  }
  const failed = new Set();

  function search(nodes) {
    if (nodes.length === 1) {
      return nodes[0].value.equals(24n) ? nodes[0].expression : null;
    }
    // Failed states need only exact values, not the route used to obtain them.
    // Every node still represents a disjoint set of original card instances.
    const state = nodes.map(node => valueKey(node.value)).sort().join('|');
    if (failed.has(state)) return null;

    for (let i = 0; i < nodes.length; i += 1) {
      for (let j = i + 1; j < nodes.length; j += 1) {
        const a = nodes[i];
        const b = nodes[j];
        const rest = nodes.filter((_, index) => index !== i && index !== j);
        const combined = [
          [a.value.add(b.value), `(${a.expression}+${b.expression})`],
          [a.value.mul(b.value), `(${a.expression}*${b.expression})`],
          [a.value.sub(b.value), `(${a.expression}-${b.expression})`],
          [b.value.sub(a.value), `(${b.expression}-${a.expression})`]
        ];
        if (b.value.n !== 0n) {
          combined.push([a.value.div(b.value), `(${a.expression}/${b.expression})`]);
        }
        if (a.value.n !== 0n) {
          combined.push([b.value.div(a.value), `(${b.expression}/${a.expression})`]);
        }
        // Addition/multiplication use one order; subtraction/division use both.
        // Equal results for this same pair have identical future possibilities.
        const seen = new Set();
        for (const [value, expression] of combined) {
          const key = valueKey(value);
          if (seen.has(key)) continue;
          seen.add(key);
          const solution = search([...rest, { value, expression }]);
          if (solution !== null) return solution;
        }
      }
    }
    failed.add(state);
    return null;
  }

  return search(cards.map(card => ({
    value: new Fraction(BigInt(card)),
    expression: String(card)
  })));
}

function generatePool() {
  const pool = [];
  for (let a = 1; a <= 9; a += 1) {
    for (let b = a; b <= 9; b += 1) {
      for (let c = b; c <= 9; c += 1) {
        for (let d = c; d <= 9; d += 1) {
          const cards = [a, b, c, d];
          const expression = solveCards(cards);
          pool.push({ id: `24-${cards.join('')}`, cards, solvable: expression !== null, expression });
        }
      }
    }
  }
  const solvable = pool.filter(record => record.solvable).length;
  if (pool.length !== 495 || solvable !== 404) {
    throw new Error(`Unexpected pool counts: ${pool.length} total, ${solvable} solvable.`);
  }
  return pool;
}

function renderData(pool) {
  return '// Generated by tools/generate-24.cjs; do not edit by hand.\n' +
    '// F3 content version 1: all 495 multisets of four cards in 1..9.\n' +
    '// Exact Fraction.js BigInt pair reduction; 404 solvable, 91 unsolvable.\n' +
    'window.MindOrbit = window.MindOrbit || {};\n' +
    `window.MindOrbit.twentyFourVersion = '${CONTENT_VERSION}';\n` +
    'window.MindOrbit.twentyFour = [\n' +
    pool.map(record => `  ${JSON.stringify(record)}`).join(',\n') +
    '\n];\n';
}

if (require.main === module) {
  const pool = generatePool();
  const output = resolve(__dirname, '../js/data/twenty-four.js');
  writeFileSync(output, renderData(pool), 'utf8');
  console.log(`Generated ${output}: 495 records, 404 solvable, 91 unsolvable.`);
}

module.exports = { CONTENT_VERSION, solveCards, generatePool, renderData };
